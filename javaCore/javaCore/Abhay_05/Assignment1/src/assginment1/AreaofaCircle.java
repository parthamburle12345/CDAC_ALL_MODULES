package assginment1;

public class AreaofaCircle {
	public static void main(String[] args) {
		float r = 5.0f;
		float pi = 3.14f;

		double area = pi * r * r;
		double circumference = 2 * pi * r;

		System.out.println("area of a circle is " + " " + area);
		System.out.println("circumference of a circle is" + " " + circumference);

	}

}
