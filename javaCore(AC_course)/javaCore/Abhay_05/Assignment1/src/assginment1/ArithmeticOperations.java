package assginment1;

public class ArithmeticOperations {
	public static void main(String[] args) {
		int x = 10;
		int y = 20;

		System.out.println("Sum of two number is" + " " + (x + y));
		System.out.println("Subtraction of two number is" + " " + (y - x));
		System.out.println("Product of two number is" + " " + (x * y));
		System.out.println("Division of two number is" + " " + (y / x));
		System.out.println("Remainder is" + " " + (y % x));

	}
}
